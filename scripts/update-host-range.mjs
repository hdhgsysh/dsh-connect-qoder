/**
 * Regenerate `test/host-range.golden.json` from the public registry.
 *
 * Run: node scripts/update-host-range.mjs            # write the golden file
 *      node scripts/update-host-range.mjs --check    # print the diff, write nothing
 *
 * WHY A GENERATOR AND NOT A LIVE FETCH IN THE GATE
 *
 * The gate has to run on a bare checkout with no network (`README` promises
 * `npm test` works before `npm install`; CI runs the test job offline too).
 * So the version universe is frozen into a committed JSON file, and this script
 * is the only thing that talks to the registry. The generator and the gate share
 * `test/helpers/host-range.mjs`, so the writer and the checker cannot disagree.
 *
 * WHY THE UNIVERSE IS `@deepseek-ai/dsh` AND NOT EACH PEER PACKAGE
 *
 * Because the host does not judge ranges against the peer package's version —
 * it judges them against ITS OWN runtime version:
 *
 *   dsh-app-boot/lib/index.js
 *   semver.satisfies(runtimeVersion, range, { includePrerelease: true })
 *
 * `@deepseek-ai/dsh-settings@0.1.2-alpha.3` is a fact about that package's
 * publish cadence, not about any host that will load this plugin. The only
 * versions a peer range ever sees are DSH runtime versions, so that is the
 * universe every range is scored against. (The package lists differ by two
 * entries anyway; using one list removes the question.)
 *
 * WHAT A RED GATE MEANS — AND WHAT IT DOES NOT
 *
 * `verdicts-moved` means upstream published a runtime version whose placement
 * relative to the committed range differs from the recorded one. That is a
 * fact about the version universe, NOT proof the plugin is broken on it: it
 * says "the range and the world have drifted apart, decide". The comment
 * written into the golden file records that distinction so a future reader
 * does not mistake this gate for an install test.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { execSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { hostPeers, partition, sortVersions } from '../test/helpers/host-range.mjs'

const REPO_ROOT = fileURLToPath(new URL('../', import.meta.url))
const GOLDEN = `${REPO_ROOT}test/host-range.golden.json`
const UNIVERSE_PACKAGE = '@deepseek-ai/dsh'
const checkOnly = process.argv.includes('--check')

/**
 * `npm view <pkg> versions --json` — the full published list, prereleases included.
 *
 * On Windows `npm` is a `.cmd` shim, which `execFileSync` cannot spawn without a
 * shell (`spawnSync npm ENOENT`, errno -4058). `execSync` with a command string
 * avoids that, and it is safe here because the package name is a constant in
 * this file — no user input ever reaches the command line.
 *
 * (Do NOT reach for `execFileSync(..., { shell: true })`: Node 24 raises
 * DEP0190 for it, and the file would then carry a permanent warning.)
 */
function fetchVersions(packageName) {
  const raw = execSync(`npm view ${packageName} versions --json`, {
    encoding: 'utf8',
    // npm prints warnings on stderr; only stdout is JSON. A cold cache is fine,
    // this script is not on the hot path of anything.
    stdio: ['ignore', 'pipe', 'inherit'],
  })
  const parsed = JSON.parse(raw)
  // A single-version package comes back as a bare string, not an array.
  return sortVersions(Array.isArray(parsed) ? parsed : [parsed])
}

/**
 * DSH runtime versions this plugin has actually been exercised on.
 *
 * NOT derived from this machine — that would make the golden file differ
 * between a developer's box and CI, and a golden file that changes with the
 * machine is a golden file nobody can review. Add a version here when the
 * plugin is verified against it, and say where the evidence is.
 *
 *   0.2.0-rc.2  docs/history/0.5.0-abi-cutover.md — the field build the
 *               0.5.0 ABI cut was probed against (probe/host-compat.mjs)
 *   0.2.1-rc.2  the runtime installed on the development machine; `npm test`
 *               and the desktop build both run against it
 */
const VALIDATED_ON = ['0.2.0-rc.2', '0.2.1-rc.2']

const manifest = JSON.parse(readFileSync(`${REPO_ROOT}package.json`, 'utf8'))
const universe = fetchVersions(UNIVERSE_PACKAGE)
if (universe.length === 0) throw new Error(`${UNIVERSE_PACKAGE} returned no versions`)

for (const version of VALIDATED_ON) {
  if (!universe.includes(version)) {
    // Loud on purpose: a version that quietly vanished from the registry means
    // the evidence line in docs/history now points at nothing.
    console.error(`WARNING: validatedOn ${version} is not in the published universe any more`)
  }
}

const peers = {}
for (const [name, range] of hostPeers(manifest)) {
  const { admitted } = partition(universe, range)
  peers[name] = { range, admitted }
}

const golden = {
  $comment: [
    'GENERATED by scripts/update-host-range.mjs — do not hand-edit.',
    '',
    'universe:    every published version of @deepseek-ai/dsh, sorted ascending.',
    'validatedOn: the runtime versions this plugin has actually been run on.',
    'peers:       each host-gated peer range from package.json, with the subset of',
    '             the universe the host would accept for it.',
    '',
    'A failure in test/host-range.test.mjs means the version universe or a range',
    'moved. Re-run the script and review the diff: a version leaving `admitted`',
    'is either a range that needs widening or a host line this plugin genuinely',
    'drops. Neither is decided by editing this file by hand.',
  ],
  universePackage: UNIVERSE_PACKAGE,
  universe,
  validatedOn: VALIDATED_ON,
  peers,
}

const serialized = `${JSON.stringify(golden, null, 2)}\n`

if (checkOnly) {
  let current = null
  try {
    current = readFileSync(GOLDEN, 'utf8')
  } catch {
    console.error(`${GOLDEN} does not exist yet`)
    process.exitCode = 1
  }
  if (current !== null) {
    if (current === serialized) {
      console.log(`golden file is current (${universe.length} versions, ${Object.keys(peers).length} peers)`)
    } else {
      const before = JSON.parse(current)
      const added = universe.filter((v) => !before.universe.includes(v))
      const removed = before.universe.filter((v) => !universe.includes(v))
      for (const v of added) console.log(`+ universe ${v}`)
      for (const v of removed) console.log(`- universe ${v}`)
      for (const [name, entry] of Object.entries(peers)) {
        const prior = before.peers?.[name]
        if (!prior) {
          console.log(`+ peer ${name} "${entry.range}" (new)`)
          continue
        }
        if (prior.range !== entry.range) console.log(`~ peer ${name} range ${prior.range} -> ${entry.range}`)
        for (const v of entry.admitted.filter((x) => !prior.admitted.includes(x))) console.log(`+ ${name} admits ${v}`)
        for (const v of prior.admitted.filter((x) => !entry.admitted.includes(x))) console.log(`- ${name} refuses ${v}`)
      }
      console.error('golden file is STALE — re-run without --check to rewrite it')
      process.exitCode = 1
    }
  }
} else {
  writeFileSync(GOLDEN, serialized)
  console.log(`wrote ${GOLDEN}: ${universe.length} versions, ${Object.keys(peers).length} peers`)
  for (const [name, entry] of Object.entries(peers)) {
    console.log(`  ${name.padEnd(42)} ${String(entry.admitted.length).padStart(2)}/${universe.length}  ${entry.range}`)
  }
}
